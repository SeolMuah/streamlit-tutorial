import streamlit as st
import pandas as pd

# =============================================================================
# 1. 페이지 제목과 헤더 구성
# =============================================================================

# 메인 제목 설정 (페이지 상단에 큰 글씨로 표시)
st.title("Streamlit 기본 출력 함수들")

# 대제목 (제목보다 작지만 눈에 띄는 헤더)
st.header("1. 텍스트 출력")

# 소제목 (헤더보다 작은 크기의 제목)
st.subheader("다양한 텍스트 표시 방법")

# =============================================================================
# 2. 기본 텍스트 출력
# =============================================================================

# 일반 텍스트 출력 (포맷팅 없는 평문)
st.text("이것은 일반 텍스트입니다.")

# 만능 출력 함수 - 텍스트, HTML, 마크다운, 데이터프레임 등 모든 것을 출력 가능
st.write("**st.write()는 만능 함수입니다!**")

# =============================================================================
# 3. 마크다운 형식 텍스트
# =============================================================================

# 마크다운 문법을 사용하여 서식이 있는 텍스트 출력
st.markdown("""
### 마크다운 지원
- **굵은 글씨**
- *기울임체*
- `코드`
- [링크](https://streamlit.io)
""")

# =============================================================================
# 4. 코드 블록 표시
# =============================================================================

# 구문 강조가 적용된 코드 블록 출력
st.code("""
def hello():
    print("Hello Streamlit!")
""", language='python')  # 언어 지정으로 구문 강조 활성화

# =============================================================================
# 5. 상태 메시지 (알림창 스타일)
# =============================================================================

# 성공 메시지 (녹색 배경)
st.success("✅ 성공 메시지")

# 경고 메시지 (노란색 배경)
st.warning("⚠️ 경고 메시지")

# 에러 메시지 (빨간색 배경)
st.error("❌ 에러 메시지")

# 정보 메시지 (파란색 배경)
st.info("ℹ️ 정보 메시지")

# =============================================================================
# 6. 데이터 표시 섹션
# =============================================================================

st.header("2. 데이터 표시")

# 샘플 데이터 딕셔너리 생성
data = {
    '이름': ['김철수', '이영희', '박민수'],
    '나이': [25, 30, 35],
    '도시': ['서울', '부산', '대구']
}

# 딕셔너리를 pandas 데이터프레임으로 변환
df = pd.DataFrame(data)

# =============================================================================
# 6-1. 인터랙티브 데이터프레임
# =============================================================================

st.subheader("📋 데이터프레임")
# 정렬, 필터링, 크기 조정이 가능한 인터랙티브 테이블
st.dataframe(df)

# =============================================================================
# 6-2. 정적 테이블
# =============================================================================

st.subheader("📊 정적 테이블")
# 상호작용 불가능한 고정된 형태의 테이블
st.table(df)

# =============================================================================
# 7. 메트릭 카드 (KPI 대시보드 스타일)
# =============================================================================

st.header("3. 메트릭 카드")

# 화면을 3개의 열로 분할하여 레이아웃 구성
col1, col2, col3 = st.columns(3)

# 첫 번째 열: 사용자 수 메트릭
with col1:
    # label: 메트릭 이름, value: 현재 값, delta: 변화량
    st.metric(label="총 사용자", value="1,234", delta="12")

# 두 번째 열: 매출 메트릭
with col2:
    # delta에 음수나 퍼센트를 넣으면 빨간색으로 표시됨
    st.metric(label="매출", value="₩12,345,678", delta="-2.3%")

# 세 번째 열: 성장률 메트릭
with col3:
    # delta에 양수를 넣으면 녹색으로 표시됨
    st.metric(label="성장률", value="15.2%", delta="1.2%")