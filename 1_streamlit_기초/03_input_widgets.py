import streamlit as st
import datetime

st.title("Streamlit 입력 위젯들")

# =============================================================================
# 1. 텍스트 입력
# =============================================================================
st.header("1. 텍스트 입력")

# 기본 텍스트 입력 위젯
name = st.text_input("이름을 입력하세요", placeholder="홍길동")
st.write(f"입력한 이름: {name}")

# =============================================================================
# 2. 숫자 입력
# =============================================================================
st.header("2. 숫자 입력")

# 숫자 전용 입력 위젯 (범위 제한 및 증감 버튼 제공)
age = st.number_input("나이를 입력하세요", min_value=0, max_value=150, value=25, step=1)
st.write(f"입력한 나이: {age}세")

# =============================================================================
# 3. 슬라이더
# =============================================================================
st.header("3. 슬라이더")

# 단일값 슬라이더
temperature = st.slider("온도 설정", min_value=-10, max_value=40, value=20, step=1)
st.write(f"설정 온도: {temperature}°C")

# 범위 슬라이더 (튜플 값으로 시작/끝 지정)
price_range = st.slider(
    "가격 범위 선택",
    min_value=0,
    max_value=1000000,
    value=(100000, 500000),  # 기본값 범위 (시작값, 끝값)
    step=10000,
    format="₩%d"  # 표시 형식 지정
)
st.write(f"선택된 가격 범위: ₩{price_range[0]:,} ~ ₩{price_range[1]:,}")

# =============================================================================
# 4. 선택 상자 (드롭다운)
# =============================================================================
st.header("4. 선택 상자")

# 드롭다운 메뉴로 단일 항목 선택
city = st.selectbox(
    "거주 도시를 선택하세요",
    ["서울", "부산", "대구", "인천", "광주", "대전", "울산"]
)
st.write(f"선택한 도시: {city}")

# =============================================================================
# 5. 다중 선택
# =============================================================================
st.header("5. 다중 선택")

# 여러 항목을 동시에 선택 가능한 위젯
hobbies = st.multiselect(
    "취미를 선택하세요 (복수 선택 가능)",
    ["영화 감상", "독서", "운동", "음악 감상", "여행", "요리", "게임"],
    default=["독서", "운동"]  # 기본 선택값
)
st.write(f"선택한 취미: {', '.join(hobbies)}")

# =============================================================================
# 6. 라디오 버튼
# =============================================================================
st.header("6. 라디오 버튼")

# 단일 선택 라디오 버튼 (모든 옵션이 화면에 표시됨)
gender = st.radio(
    "성별을 선택하세요",
    ["남성", "여성", "기타"],
    horizontal=True  # 가로 배열 (기본값: 세로)
)
st.write(f"선택한 성별: {gender}")

# =============================================================================
# 7. 체크박스
# =============================================================================
st.header("7. 체크박스")

# 불린(True/False) 값을 반환하는 체크박스
agree = st.checkbox("개인정보 처리방침에 동의합니다")
newsletter = st.checkbox("뉴스레터 수신에 동의합니다", value=True)  # 기본값 체크

# 조건부 메시지 표시
if agree:
    st.success("✅ 개인정보 처리방침에 동의하셨습니다")
else:
    st.warning("⚠️ 개인정보 처리방침 동의가 필요합니다")

# =============================================================================
# 8. 버튼
# =============================================================================
st.header("8. 버튼")

# 기본 버튼 (클릭시 True 반환, 아니면 False)
if st.button("👋 인사하기", type="primary"):
    st.balloons()  # 풍선 효과!
    st.success(f"안녕하세요, {name}님!")

# 다양한 버튼 타입 데모
col1, col2 = st.columns(2)

with col1:
    if st.button("기본 버튼"):
        st.info("기본 버튼 클릭!")

with col2:
    if st.button("Primary", type="primary"):
        st.snow()  # 눈이 내림 효과!
        st.info("Primary 버튼 클릭!")
        

# =============================================================================
# 9. 날짜/시간 입력
# =============================================================================
st.header("9. 날짜/시간 입력")

# 날짜 선택기
birthday = st.date_input("생일을 선택하세요", value=datetime.date(2000, 1, 1))

# 시간 선택기
appointment_time = st.time_input("약속 시간을 선택하세요", value=datetime.time(14, 30), step=datetime.timedelta(minutes=5))

st.write(f"생일: {birthday}")
st.write(f"약속 시간: {appointment_time}")